#!/usr/bin/env bash
# Monitoring stack: Prometheus + Grafana + blackbox_exporter via docker-compose,
# on the dedicated `mon` node. node_exporter is NOT part of this stack — it
# runs natively on every node instead (common.sh), so Prometheus gets real
# per-host kernel uptime rather than only ever seeing mon's own.
# Brought up AHEAD OF TIME: during the webinar we show a ready dashboard, no
# airtime spent installing it. Idempotent (compose up -d).
#
# NODE_TARGETS / WEB_TARGETS / DB_TARGETS come from the Vagrantfile as
# space-separated "name=ip" pairs, already filtered to whatever this
# profile (full/lite) actually brings up — see nodes.json (the topology's
# single source of truth) and Vagrantfile's NODE_TARGETS/WEB_TARGETS/
# DB_TARGETS. This is how prometheus.yml avoids static targets for prod
# nodes that don't exist under STAND_PROFILE=lite (they'd sit DOWN forever
# and ruin the continuity demo).
set -euo pipefail

: "${NODE_TARGETS:?NODE_TARGETS must be set (name=ip pairs) — see Vagrantfile}"
: "${WEB_TARGETS:?WEB_TARGETS must be set (name=ip pairs) — see Vagrantfile}"
: "${DB_TARGETS:?DB_TARGETS must be set (name=ip pairs) — see Vagrantfile}"

if ! command -v docker >/dev/null 2>&1; then
	# Install Docker Engine (Ubuntu). Once.
	export DEBIAN_FRONTEND=noninteractive
	apt-get update -y
	apt-get install -y docker.io docker-compose-v2
	systemctl enable --now docker
fi

# Registry mirrors — guards against Docker Hub rate limits when many students
# pull the same images (Prometheus/Grafana/exporters) at once from home.
if [ ! -f /etc/docker/daemon.json ]; then
	mkdir -p /etc/docker
	printf '{"registry-mirrors":["https://mirror.gcr.io"]}\n' > /etc/docker/daemon.json
	systemctl restart docker
fi

# Work from a local copy, not the /monitoring synced folder directly: that
# folder is bind-mounted from the host repo checkout (../monitoring in the
# Vagrantfile), and prometheus.yml below is regenerated per-profile on every
# provision run — writing that back into the host's working tree would
# silently dirty the repo on every `vagrant up`/`vagrant provision`.
STACK_DIR=/opt/monitoring
mkdir -p "$STACK_DIR"
cp -a /monitoring/. "$STACK_DIR/"

# --- generate prometheus.yml for exactly the nodes this profile brings up ---
PROM_CONF="$STACK_DIR/prometheus/prometheus.yml"
mkdir -p "$STACK_DIR/prometheus"

{
	echo "# GENERATED by stand/provision/monitoring.sh from nodes.json + the active"
	echo "# profile (STAND_PROFILE) — do not hand-edit; edit nodes.json or this"
	echo "# script instead, then re-provision mon. Check metric names against the"
	echo "# real exporters (rules/configs.md) — no dead panels allowed."
	echo "global:"
	echo "  scrape_interval: 5s"
	echo
	echo "scrape_configs:"

	# job: node — node_exporter on every active node (web/db/mon), instance
	# label set to the node's name from nodes.json instead of the bare
	# "ip:9100" address, so Grafana legends read "web-stage" not an IP.
	echo "  - job_name: node"
	echo "    static_configs:"
	for pair in $NODE_TARGETS; do
		name="${pair%%=*}"
		ip="${pair#*=}"
		echo "      - targets: [\"${ip}:9100\"]"
		echo "        labels:"
		echo "          instance: \"${name}\""
	done
	echo

	# job: blackbox-http — WordPress availability on every active web node.
	# instance label is set to the node name (not the probed URL) so the
	# Grafana panels read "web-stage", matching the node job's legends —
	# the __param_target relabel carries the real URL to probe separately.
	echo "  - job_name: blackbox-http"
	echo "    metrics_path: /probe"
	echo "    params:"
	echo "      module: [http_2xx]"
	echo "    static_configs:"
	for pair in $WEB_TARGETS; do
		name="${pair%%=*}"
		ip="${pair#*=}"
		echo "      - targets: [\"http://${ip}\"]"
		echo "        labels:"
		echo "          instance: \"${name}\""
		echo "          service: \"nginx\""
	done
	echo "    relabel_configs:"
	echo "      - source_labels: [__address__]"
	echo "        target_label: __param_target"
	echo "      - target_label: __address__"
	echo "        replacement: blackbox_exporter:9115"
	echo

	# job: blackbox-tcp — MySQL reachability on every active db node.
	# instance label = node name (see blackbox-http above for why).
	echo "  - job_name: blackbox-tcp"
	echo "    metrics_path: /probe"
	echo "    params:"
	echo "      module: [tcp_connect]"
	echo "    static_configs:"
	for pair in $DB_TARGETS; do
		name="${pair%%=*}"
		ip="${pair#*=}"
		echo "      - targets: [\"${ip}:3306\"]"
		echo "        labels:"
		echo "          instance: \"${name}\""
		echo "          service: \"mysql\""
	done
	echo "    relabel_configs:"
	echo "      - source_labels: [__address__]"
	echo "        target_label: __param_target"
	echo "      - target_label: __address__"
	echo "        replacement: blackbox_exporter:9115"
} > "$PROM_CONF"

echo "monitoring: generated prometheus.yml -- node: $(echo "$NODE_TARGETS" | wc -w | tr -d ' ') targets, web: $(echo "$WEB_TARGETS" | wc -w | tr -d ' '), db: $(echo "$DB_TARGETS" | wc -w | tr -d ' ')"

# Dashboards and datasources — provisioned from files in the repo (no manual UI).
docker compose -f "$STACK_DIR/docker-compose.yml" up -d
# Config may have changed since the last provision run (e.g. a node's IP
# changed, or a re-provision under a different profile) -- compose up -d
# alone won't pick up a changed bind-mounted file, so make Prometheus
# actually reload it every run (idempotent: a no-op reload if nothing changed).
docker compose -f "$STACK_DIR/docker-compose.yml" restart prometheus

echo "monitoring: stack is up (Grafana on :3000, Prometheus on :9090)"
